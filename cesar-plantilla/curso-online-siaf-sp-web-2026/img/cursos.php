/* 2. Función auxiliar para convertir fecha texto a DateTime */

function parseFecha($fechaTexto) {
    $fechaTexto = strtoupper(trim($fechaTexto));
    
    $meses = [
        'ENERO'=>1, 'ENE'=>1, 
        'FEBRERO'=>2, 'FEB'=>2, 
        'MARZO'=>3, 'MAR'=>3, 
        'ABRIL'=>4, 'ABR'=>4, 'ABRI'=>4,
        'MAYO'=>5, 'MAY'=>5, 
        'JUNIO'=>6, 'JUN'=>6, 
        'JULIO'=>7, 'JUL'=>7, 
        'AGOSTO'=>8, 'AGO'=>8, 
        'SEPTIEMBRE'=>9, 'SET'=>9, 'SEP'=>9,
        'OCTUBRE'=>10, 'OCT'=>10,
        'NOVIEMBRE'=>11, 'NOV'=>11,
        'DICIEMBRE'=>12, 'DIC'=>12
    ];
    
    preg_match('/(\d+)\s*([A-Z]{3,5})/', $fechaTexto, $matches);
    if (empty($matches)) return new DateTime('now', new DateTimeZone('America/Lima'));
    
    $dia = (int)$matches[1];
    $mesNombre = $matches[2];
    $mes = $meses[$mesNombre] ?? 1;
    
    return new DateTime("2026-{$mes}-{$dia}", new DateTimeZone('America/Lima'));
}

